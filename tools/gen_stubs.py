#!/usr/bin/env python3
"""Generate chapter stubs and the chapter list of _quarto.yml from outline/chapters.yml.

OPTIONAL. A small book can simply list its chapters in _quarto.yml by hand. For
a large book, keep the structure in outline/chapters.yml (the single source of
truth) and run this after every change to it:

    python tools/gen_stubs.py            # missing stubs + chapter list
    python tools/gen_stubs.py --check    # exit 1 if _quarto.yml is out of date (CI)
    python tools/gen_stubs.py --force    # also overwrite existing stub files (!)

What it does:
  * writes chapters/NN-slug.qmd and appendices/ID-slug.qmd stubs for entries
    that have no file yet (existing files are never touched without --force),
  * rewrites ONLY the lines between the two marker comments in _quarto.yml:

        # >>> chapters: generated by tools/gen_stubs.py -- do not edit >>>
        # <<< chapters <<<

    Everything else in _quarto.yml (title, formats, filters, ...) stays
    hand-edited, so there is no second copy of the configuration to keep in sync.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required: pip install -r requirements.txt")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTLINE = os.path.join(ROOT, "outline", "chapters.yml")
QUARTO_YML = os.path.join(ROOT, "_quarto.yml")
BEGIN = "# >>> chapters: generated by tools/gen_stubs.py -- do not edit >>>"
END = "# <<< chapters <<<"


def chapter_path(ch: dict) -> str:
    return f"chapters/{int(ch['n']):02d}-{ch['slug']}.qmd"


def appendix_path(ap: dict) -> str:
    return f"appendices/{ap['id']}-{ap['slug']}.qmd"


def quote(text: str) -> str:
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def chapter_stub(ch: dict) -> str:
    prereqs = ch.get("prereqs") or []
    prereq = ("فصل‌های " + "، ".join(str(p) for p in prereqs)) if prereqs else "ندارد"
    objectives = "\n".join(f"  - {o}" for o in ch.get("objectives") or [])
    return f"""---
title: {quote(ch['title_fa'])}
---

<!--
  PLANNING METADATA (author-facing; not rendered)
  chapter   : {ch['n']}
  title_en  : {ch.get('title_en', '')}
  est_pages : {ch.get('pages', '?')}
  objectives:
{objectives}
-->

::: {{.callout-note}}
## اهداف یادگیری
<!-- TODO -->
:::

**پیش‌نیازها:** {prereq}

## درآمد

<!-- TODO -->

## بدنهٔ فصل

<!-- TODO -->

## جمع‌بندی

<!-- TODO -->

## پرسش‌ها و تمرین‌ها

<!-- TODO -->
"""


def appendix_stub(ap: dict) -> str:
    return f"""---
title: {quote(ap['title_fa'])}
---

<!-- title_en: {ap.get('title_en', '')} -->

<!-- TODO -->
"""


def chapter_block(outline: dict) -> list[str]:
    """The generated lines: the rest of `book: chapters:` and `book: appendices:`."""
    lines = []
    for ch in outline.get("chapters") or []:
        lines.append(f"    - {chapter_path(ch)}")
    for part in outline.get("parts") or []:
        lines.append(f"    - part: {quote(part['title_fa'])}")
        lines.append("      chapters:")
        for ch in part.get("chapters") or []:
            lines.append(f"        - {chapter_path(ch)}")
    appendices = outline.get("appendices") or []
    if appendices:
        lines.append("  appendices:")
        for ap in appendices:
            lines.append(f"    - {appendix_path(ap)}")
    return lines


def all_chapters(outline: dict) -> list[dict]:
    chapters = list(outline.get("chapters") or [])
    for part in outline.get("parts") or []:
        chapters += part.get("chapters") or []
    return chapters


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="overwrite existing stub files")
    ap.add_argument("--check", action="store_true",
                    help="change nothing; exit 1 if _quarto.yml or a stub is missing/out of date")
    args = ap.parse_args()

    if not os.path.exists(OUTLINE):
        sys.exit("gen_stubs: no outline/chapters.yml (see the comments at the top of this script)")
    with open(OUTLINE, encoding="utf-8") as fh:
        outline = yaml.safe_load(fh) or {}

    chapters = all_chapters(outline)
    numbers = [int(c["n"]) for c in chapters]
    dupes = sorted({n for n in numbers if numbers.count(n) > 1})
    if dupes:
        sys.exit(f"gen_stubs: duplicate chapter numbers in the outline: {dupes}")

    with open(QUARTO_YML, encoding="utf-8") as fh:
        text = fh.read()
    pattern = re.compile(r"^[ \t]*" + re.escape(BEGIN) + r"\n.*?^[ \t]*" + re.escape(END) + r"[ \t]*\n",
                         re.S | re.M)
    if not pattern.search(text):
        sys.exit("gen_stubs: _quarto.yml has no marker comments. Put these two lines at the "
                 f"end of the `book: chapters:` list (after index.qmd):\n    {BEGIN}\n    {END}")
    block = "\n".join([f"    {BEGIN}"] + chapter_block(outline) + [f"    {END}"]) + "\n"
    new_text = pattern.sub(lambda _m: block, text, count=1)

    todo = [(chapter_path(c), chapter_stub(c)) for c in chapters]
    todo += [(appendix_path(a), appendix_stub(a)) for a in outline.get("appendices") or []]
    missing = [rel for rel, _ in todo if not os.path.exists(os.path.join(ROOT, rel))]

    if args.check:
        problems = (["_quarto.yml chapter list differs from the outline"] if new_text != text else [])
        problems += [f"missing {rel}" for rel in missing]
        for p in problems:
            print("gen_stubs: " + p)
        print("gen_stubs: " + ("run `python tools/gen_stubs.py`" if problems else "up to date"))
        return 1 if problems else 0

    written = 0
    for rel, content in todo:
        path = os.path.join(ROOT, rel)
        if os.path.exists(path) and not args.force:
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        written += 1
    if new_text != text:
        with open(QUARTO_YML, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new_text)
    print(f"gen_stubs: {len(chapters)} chapter(s), {len(outline.get('appendices') or [])} appendix(es); "
          f"{written} stub(s) written, {len(todo) - written} existing file(s) left alone; "
          f"_quarto.yml {'updated' if new_text != text else 'already up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
